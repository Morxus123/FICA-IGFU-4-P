def unit_signature(unit: str) -> dict:
    if unit not in UNITS:
        raise ValueError("unknown base unit")
    return dict(UNITS[unit])

def combine_units(a: dict, b: dict, sign: int = 1) -> dict:
    out = dict(a)
    for k, v in b.items():
        out[k] = out.get(k, 0) + sign * v
        if out[k] == 0:
            del out[k]
    return out

def unit_product(u1: str, u2: str) -> dict:
    return combine_units(unit_signature(u1), unit_signature(u2), 1)

def unit_division(u1: str, u2: str) -> dict:
    return combine_units(unit_signature(u1), unit_signature(u2), -1)

def validate_measurement(req: dict) -> dict:
    if not isinstance(req.get("value"), (int, float)):
        raise ValueError("measurement value must be numeric")
    unit = req.get("unit")
    unit_signature(unit)
    uncertainty = req.get("uncertainty", 0)
    if not isinstance(uncertainty, (int, float)) or uncertainty < 0:
        raise ValueError("uncertainty must be non-negative")
    if uncertainty > abs(req["value"]) and req["value"] != 0:
        relative = None
    else:
        relative = uncertainty / abs(req["value"]) if req["value"] != 0 else None
    payload = {
        "value": req["value"],
        "unit": unit,
        "uncertainty": uncertainty,
        "relative_uncertainty": relative,
        "exact": uncertainty == 0,
        "unit_signature": unit_signature(unit),
    }
    return {
        "valid": True,
        "measurement": payload,
        "digest": kernel_digest(payload),
        "status": "measurement_validated",
        "empirical_truth_proved": False,
    }

def propagate_add(m1: dict, m2: dict) -> dict:
    if m1["unit"] != m2["unit"]:
        raise ValueError("addition requires identical units in v3.0")
    value = m1["value"] + m2["value"]
    uncertainty = (m1["uncertainty"]**2 + m2["uncertainty"]**2) ** 0.5
    return {"value": value, "unit": m1["unit"], "uncertainty": uncertainty,
            "method": "root_sum_square_independent"}

def validate_experiment(exp: dict) -> dict:
    if not isinstance(exp.get("id"), str) or not exp["id"]:
        raise ValueError("experiment requires id")
    if not isinstance(exp.get("inputs"), list):
        raise ValueError("experiment inputs must be list")
    for item in exp["inputs"]:
        validate_measurement(item)
    result = exp.get("result")
    if result is not None:
        validate_measurement(result)
    payload = {
        "id": exp["id"],
        "inputs": exp["inputs"],
        "method": exp.get("method", ""),
        "result": result,
    }
    return {
        "valid": True,
        "id": exp["id"],
        "input_count": len(exp["inputs"]),
        "has_result": result is not None,
        "digest": kernel_digest(payload),
        "status": "experiment_schema_validated",
        "empirical_truth_proved": False,
    }

