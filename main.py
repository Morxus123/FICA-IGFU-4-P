def digest(payload):
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest()

def apply_operator(name, args, modulus=None):
    if name not in OPERATORS:
        raise ValueError("unknown operator")
    if len(args) != OPERATORS[name]["arity"]:
        raise ValueError("wrong arity")
    a = args[0]
    if name == "add": return a + args[1]
    if name == "subtract": return a - args[1]
    if name == "multiply": return a * args[1]
    if name == "divide_floor":
        if args[1] == 0: raise ValueError("division by zero")
        return a // args[1]
    if name == "modulo":
        if args[1] == 0: raise ValueError("modulo by zero")
        return a % args[1]
    if name == "add_mod":
        if modulus is None or modulus <= 0: raise ValueError("positive modulus required")
        return (a + args[1]) % modulus
    if name == "multiply_mod":
        if modulus is None or modulus <= 0: raise ValueError("positive modulus required")
        return (a * args[1]) % modulus
    if name == "collatz_step":
        if a <= 0: raise ValueError("positive integer required")
        return a // 2 if a % 2 == 0 else 3 * a + 1
    raise ValueError("operator not implemented")

def iterate(name, initial, steps, modulus=None):
    if steps < 0 or steps > 100000:
        raise ValueError("steps must be 0..100000")
    state = initial
    trajectory = [state]
    for _ in range(steps):
        state = apply_operator(name, [state] if OPERATORS[name]["arity"] == 1 else [state, 0], modulus)
        trajectory.append(state)
    payload = {"domain": OPERATORS[name]["domain"], "operator": name,
               "initial": initial, "steps": steps, "terminal": state,
               "trajectory": trajectory}
    return {**payload, "certificate": {
        "version": "1.1.0", "digest": digest(payload),
        "attestation": "reproducible_computation", "theorem_proved": False
    }}

