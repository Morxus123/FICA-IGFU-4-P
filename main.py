def normalize_algebra(expr: str) -> str:
    # Restricted, deterministic integer/symbolic rewrite engine.
    # This is intentionally not a full CAS.
    s = expr.replace(" ", "")
    if not s:
        raise ValueError("empty expression")
    changed = True
    while changed:
        changed = False
        replacements = [
            ("+0", ""),
            ("*1", ""),
            ("1*", ""),
            ("*0", "*0"),
            ("--", ""),
        ]
        for old, new in replacements:
            if old in s:
                ns = s.replace(old, new)
                if ns != s:
                    s, changed = ns, True
    if s.endswith("*0") or s.startswith("0*"):
        return "0"
    return s

def algebra_equivalent(left: str, right: str) -> dict:
    nl, nr = normalize_algebra(left), normalize_algebra(right)
    return {
        "left": left, "right": right,
        "left_normal_form": nl, "right_normal_form": nr,
        "equivalent": nl == nr,
        "ruleset": "restricted_v1.7",
        "theorem_proved": False,
    }

