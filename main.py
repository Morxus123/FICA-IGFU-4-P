@app.post("/api/evaluate")
def api_evaluate(req:EvaluateRequest):
    try:
        return iterate("collatz_step", req.n, req.max_steps)
    except ValueError as e:
        raise HTTPException(400,str(e))

@app.post("/api/search")
def api_search(req:SearchRequest):
    if req.end<req.start or req.end-req.start>5000:
        raise HTTPException(400,"invalid bounded range")
    rows=[]
    for n in range(req.start,req.end+1):
        r=evaluate(n,req.max_steps)
        rows.append({"n":n,"steps":r["steps"],"terminal":r["terminal"],"reached_1":r["terminal"]==1})
    bad=[x for x in rows if not x["reached_1"]]
    return {"tested":len(rows),"counterexamples":bad,
            "status":"no_counterexample_in_bounded_range" if not bad else "counterexample_found"}

