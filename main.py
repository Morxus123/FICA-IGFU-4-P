def build_theorem(thm: dict) -> dict:
    if not isinstance(thm.get("id"), str) or not thm["id"]:
        raise ValueError("theorem requires id")
    if not isinstance(thm.get("statement"), str) or not thm["statement"].strip():
        raise ValueError("theorem requires statement")
    assumptions = thm.get("assumptions", [])
    obligations = thm.get("obligations", [])
    if not isinstance(assumptions, list) or not isinstance(obligations, list):
        raise ValueError("assumptions and obligations must be lists")
    return {
        "id": thm["id"],
        "statement": thm["statement"],
        "assumptions": assumptions,
        "obligations": obligations,
        "status": "obligations_open" if obligations else "proposed",
        "theorem_proved": False,
        "digest": digest(thm),
    }

def discharge_obligations(thm: dict) -> dict:
    record = build_theorem(thm)
    results = []
    for i, obligation in enumerate(record["obligations"], 1):
        if not isinstance(obligation, dict):
            return {"status":"rejected","failed_obligation":i,"reason":"obligation must be object","theorem_proved":False}
        kind = obligation.get("kind")
        if kind == "finite_quantifier":
            try:
                result = check_finite_quantifier(obligation["quantifier"])
                ok = bool(result.get("satisfied"))
            except ValueError as e:
                return {"status":"rejected","failed_obligation":i,"reason":str(e),"theorem_proved":False}
        elif kind == "inference":
            try:
                result = infer(obligation["inference"])
                ok = bool(result.get("valid"))
            except ValueError as e:
                return {"status":"rejected","failed_obligation":i,"reason":str(e),"theorem_proved":False}
        else:
            return {"status":"rejected","failed_obligation":i,"reason":"unknown obligation type","theorem_proved":False}
        results.append({"index":i,"kind":kind,"ok":ok,"result":result})
        if not ok:
            return {"status":"obligations_open","failed_obligation":i,
                    "obligations":results,"theorem_proved":False,
                    "theorem":record}
    return {
        "status":"verified_derivation",
        "theorem":record,
        "obligations":results,
        "theorem_proved":False,
        "certificate":{
            "version":app.version,
            "digest":digest({"theorem":record,"obligations":results}),
            "attestation":"finite_obligation_verification"
        }
    }

