@app.post("/api/operator/apply")
def operator_apply(req: dict):
    try:
        return {"operator": req["operator"],
                "result": apply_operator(req["operator"], req["args"], req.get("modulus")),
                "theorem_proved": False}
    except (KeyError, ValueError, IndexError) as e:
        raise HTTPException(400, str(e))

