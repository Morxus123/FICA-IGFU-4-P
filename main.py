def safe_eval(expr:str)->int:
    tree=ast.parse(expr,mode="eval")
    def v(n):
        if isinstance(n,ast.Expression): return v(n.body)
        if isinstance(n,ast.Constant) and type(n.value) is int: return n.value
        if isinstance(n,ast.UnaryOp) and isinstance(n.op,(ast.UAdd,ast.USub)):
            x=v(n.operand); return x if isinstance(n.op,ast.UAdd) else -x
        if isinstance(n,ast.BinOp) and type(n.op) in BINOPS:
            a,b=v(n.left),v(n.right)
            if isinstance(n.op,(ast.FloorDiv,ast.Mod)) and b==0: raise ValueError("division by zero")
            return BINOPS[type(n.op)](a,b)
        raise ValueError("unsupported expression")
    return v(tree)

