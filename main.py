def validate_object(obj):
    kind = obj.get("type")
    if kind not in OBJECT_TYPES:
        raise ValueError("unknown object type")
    if kind == "scalar":
        if "value" not in obj:
            raise ValueError("scalar requires value")
    elif kind == "set":
        if not isinstance(obj.get("elements"), list):
            raise ValueError("set requires elements list")
    elif kind == "sequence":
        if not isinstance(obj.get("elements"), list):
            raise ValueError("sequence requires elements list")
    elif kind == "relation":
        if not isinstance(obj.get("pairs"), list):
            raise ValueError("relation requires pairs list")
    elif kind == "function":
        if not isinstance(obj.get("mapping"), dict):
            raise ValueError("function requires mapping object")
    elif kind == "operator":
        if obj.get("name") not in OPERATORS:
            raise ValueError("function/operator name is not registered")
    elif kind == "proposition":
        if not isinstance(obj.get("statement"), str) or not obj["statement"].strip():
            raise ValueError("proposition requires statement")
    elif kind == "experiment":
        if "input" not in obj or "operator" not in obj:
            raise ValueError("experiment requires input and operator")
    return {
        "valid": True,
        "type": kind,
        "schema": OBJECT_TYPES[kind],
        "digest": digest(obj),
    }

