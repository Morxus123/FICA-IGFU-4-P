def apply_function(name, x):
    if name == "identity": return x
    if name == "double": return 2*x
    if name == "square": return x*x
    if name == "collatz_step":
        if x <= 0: raise ValueError("positive integer required")
        return x//2 if x%2==0 else 3*x+1
    raise ValueError("unknown function")

def compose_functions(first, second):
    if first not in FUNCTIONS or second not in FUNCTIONS:
        raise ValueError("unknown function")
