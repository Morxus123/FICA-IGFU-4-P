INFERENCE_RULES = {
    "EQ_REFL": "x = x",
    "EQ_SYM": "x = y implies y = x",
    "EQ_TRANS": "x = y and y = z implies x = z",
    "DIVISIBLE": "a is divisible by b iff b != 0 and a mod b = 0",
}

def infer(step: dict) -> dict:
    rule = step.get("rule")
    if rule == "EQ_REFL":
        x = step.get("x")
        return {"valid": x is not None, "conclusion": {"left": x, "right": x}}
    if rule == "EQ_SYM":
        left, right = step.get("left"), step.get("right")
        if left is None or right is None:
            raise ValueError("EQ_SYM requires left and right")
        return {"valid": True, "conclusion": {"left": right, "right": left}}
    if rule == "EQ_TRANS":
        a, b, c = step.get("a"), step.get("b"), step.get("c")
        if a is None or b is None or c is None:
            raise ValueError("EQ_TRANS requires a, b, c")
        if b != step.get("middle"):
            raise ValueError("middle value must equal b")
        return {"valid": True, "conclusion": {"left": a, "right": c}}
    if rule == "DIVISIBLE":
        a, b = step.get("a"), step.get("b")
        if not isinstance(a, int) or not isinstance(b, int):
            raise ValueError("DIVISIBLE requires integer a and b")
        if b == 0:
            return {"valid": False, "reason": "zero divisor"}
        return {"valid": a % b == 0, "remainder": a % b}
    raise ValueError("unknown inference rule")

