def verify_proof_graph(graph: dict) -> dict:
    nodes = graph.get("nodes")
    if not isinstance(nodes, list) or not nodes:
        raise ValueError("proof graph requires non-empty nodes")
    by_id = {}
    for node in nodes:
        nid = node.get("id")
        if not isinstance(nid, str) or not nid:
            raise ValueError("each node requires a non-empty id")
        if nid in by_id:
            raise ValueError("duplicate node id")
        by_id[nid] = node

    verified = []
    for node in nodes:
        deps = node.get("depends_on", [])
        if not isinstance(deps, list):
            raise ValueError("depends_on must be a list")
        missing = [d for d in deps if d not in by_id]
        if missing:
            return {"status":"rejected","failed_node":node["id"],
                    "reason":"missing dependency","missing":missing,
                    "theorem_proved":False}
        rule = node.get("rule")
        if rule == "ASSUMPTION":
            ok = True
        else:
            ok = all(d in verified for d in deps)
            if rule in INFERENCE_RULES:
                try:
                    result = infer(node.get("inference", node))
                    ok = ok and bool(result.get("valid"))
                except ValueError as e:
                    return {"status":"rejected","failed_node":node["id"],
                            "reason":str(e),"theorem_proved":False}
            else:
                return {"status":"rejected","failed_node":node["id"],
                        "reason":"unknown proof rule","theorem_proved":False}
        if not ok:
            return {"status":"rejected","failed_node":node["id"],
                    "reason":"dependency or inference failed","theorem_proved":False}
        verified.append(node["id"])

    conclusion = graph.get("conclusion")
    return {
        "status":"verified_derivation",
        "verified_nodes":verified,
        "conclusion":conclusion,
        "theorem_proved":False,
        "certificate":{"version":app.version,"digest":digest(graph),
                       "attestation":"finite_proof_graph_verification"}
    }

