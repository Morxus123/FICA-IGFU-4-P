def check_finite_quantifier(q):
    if q.get("kind") not in QUANTIFIERS:
        raise ValueError("unknown quantifier")
    domain = q.get("domain")
    if not isinstance(domain, list) or not domain:
        raise ValueError("finite non-empty domain required")
    predicate = q.get("predicate")
    if not isinstance(predicate, dict):
        raise ValueError("predicate object required")
    # v1.5 supports explicit equality predicates only.
    if predicate.get("op") == "equals":
        value = predicate.get("value")
        return {
            "quantifier": q["kind"],
            "variable": q["variable"],
            "domain_size": len(domain),
            "satisfied": all(x == value for x in domain) if q["kind"] == "forall"
                         else any(x == value for x in domain),
        }
    raise ValueError("unsupported predicate; v1.5 supports equals")

