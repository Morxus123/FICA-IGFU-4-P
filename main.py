def validate_cross_domain_graph(graph):
    if not isinstance(graph,dict): raise ValueError("graph must be an object")
    nodes=graph.get("nodes")
    edges=graph.get("edges",[])
    if not isinstance(nodes,list) or not nodes: raise ValueError("nodes must be non-empty list")
    if not isinstance(edges,list): raise ValueError("edges must be a list")
    ids=set()
    normalized=[]
    for n in nodes:
        if not isinstance(n,dict) or not isinstance(n.get("id"),str):
            raise ValueError("each node requires id")
        if n["id"] in ids: raise ValueError("duplicate node id")
        if n.get("domain") not in SCIENCE_DOMAINS:
            raise ValueError("node has unknown science domain")
        if n.get("type") not in CROSS_DOMAIN_NODE_TYPES:
            raise ValueError("node has unknown type")
        ids.add(n["id"]); normalized.append(n)
    for e in edges:
        if not isinstance(e,dict) or e.get("source") not in ids or e.get("target") not in ids:
            raise ValueError("edge references unknown node")
        if not isinstance(e.get("relation"),str) or not e["relation"]:
            raise ValueError("edge requires relation")
    payload={"nodes":normalized,"edges":edges}
    return {
        "valid":True,
        "node_count":len(normalized),
        "edge_count":len(edges),
        "domains":sorted({n["domain"] for n in normalized}),
        "digest":kernel_digest(payload),
        "status":"cross_domain_graph_validated",
        "scientific_truth_proved":False,
    }

